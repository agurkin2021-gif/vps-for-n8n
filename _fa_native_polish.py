def sig(x):
    return [("/" if m.group()[1:2]=="/" else "")+m.group(1).lower()
            for m in re.finditer(r'</?([a-z][\w-]*)\b[^>]*>',x,re.I)
            if m.group(1).lower() not in ("link","meta")]

def polish(path):
    p=ROOT/path
    src=p.read_text(encoding="utf-8")
    out=src
    for a,b in sorted(REPL.items(),key=lambda kv:len(kv[0]),reverse=True):
        out=out.replace(a,b)
    if sig(src)!=sig(out):
        raise AssertionError(path+": HTML structure changed")
    if len(re.findall(r'[\u0600-\u06FF]',out))<5:
        raise AssertionError(path+": Persian missing")
    p.write_text(out,encoding="utf-8")
    print("PERSIAN_NATIVE_POLISH PASS",path,"changes",sum(src.count(a) for a in REPL),flush=True)

